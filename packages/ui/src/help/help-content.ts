/** 按语言解析某页正文：zh* → zh-CN，其余 → en-US。 */
export function resolveHelpContent(tabId: HelpTabId, language: string): string {
  const entry = HELP_CONTENT[tabId];
  const main = language.toLowerCase().startsWith("zh") ? "zh-CN" : "en-US";
  return entry[main];
}
